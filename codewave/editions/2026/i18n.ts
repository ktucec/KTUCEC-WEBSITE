// Türkçede yerleşik yazım "100 TL"; İngilizcede ISO kodu. ₺ simgesi başlık yazı tipinde küçük boyutta
// "Ł" gibi okunabildiği için kullanılmıyor.
export function formatAmount(lang: Lang, value: number) {
    const amount = new Intl.NumberFormat(lang === 'TR' ? 'tr-TR' : 'en-GB', { maximumFractionDigits: 2 }).format(value);
    const unit = TICKET.currency === 'TRY' ? (lang === 'TR' ? 'TL' : 'TRY') : TICKET.currency;
    return lang === 'TR' ? `${amount} ${unit}` : `${unit} ${amount}`;
}

export const formatPrice = (lang: Lang) => formatAmount(lang, TICKET.price);

